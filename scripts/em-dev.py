#!/usr/bin/env python3
"""Make this repo use local sibling checkouts instead of published packages.

External users install the published `emergent-matter-*` packages from the
index. Internal developers keep siblings (sdm-core, sdm-materials, ...)
checked out next to this repo and want their edits to show up immediately,
without ever touching this repo's `pyproject.toml`, `uv.lock`, or `.venv` --
those are the files a plain `git status` and a plain `uv sync` both have to
agree are untouched, in local mode or out of it.

The trick, measured against a local test index with uv 0.12.5: uv has no
supported "use local folders instead" switch (a git-ignored `uv.toml` with
`[tool.uv.sources]` is REJECTED -- uv does not accept `sources` there), so
this builds a second, git-ignored environment, `.venv-local`, from the
lock's own constraints, with local siblings installed editable on top.

Commands:

    em-dev                  make this repo use local siblings (build/refresh
                             .venv-local, and reinstall this repo's own
                             console script from local code when
                             [tool.em-dev] opts in)
    em-dev run <cmd...>      run a command inside .venv-local (--no-sync,
                             never re-syncs it)
    em-dev off               back to published: removes .venv-local (and,
                             in tool mode, reinstalls the pinned published
                             version of the console script)
    em-dev status            local vs published per package, and whether
                             local mode has silently reverted
    em-dev --only a,b        make only these packages local

Stdlib only. Runs on Python 3.9+ (what macOS ships as `python3`) -- this is
why it carries its own minimal TOML reader instead of `tomllib` (3.11+
only), and why it is invoked directly (`python3 scripts/em-dev.py ...`),
never through `uv run`: the whole point is to work before anything is
synced. In a repo with no `emergent-matter-*` dependencies it says "nothing
here to make local" and exits 0.

Distributed by `EmergentMatter/actions`: see templates/manifest.toml. Do
not add third-party imports here -- see the module docstring rule this
repo runs on py313 with, in ../STYLE.md, "no bare pip".
"""

