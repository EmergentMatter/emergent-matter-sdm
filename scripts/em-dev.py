def normalize_name(name: str) -> str:
    """PEP 503 normalization: lowercase, runs of `-_.` collapse to one `-`.

    `uv.lock` and a project's own `[project].name` may spell the same
    package with dashes or underscores; every name comparison in this
    script goes through this first so the two always compare equal.
    """
    return re.sub(r"[-_.]+", "-", name).lower()


def own_project_name(pyproject: dict) -> str:
    """The consuming repo's own package/project name, normalized."""
    name = pyproject.get("project", {}).get("name")
    if not name:
        raise EmDevError("pyproject.toml has no [project] name")
    return normalize_name(name)


def own_project_version(pyproject: dict) -> str:
    version = pyproject.get("project", {}).get("version")
    if not version:
        raise EmDevError("pyproject.toml has no [project] version")
    return str(version)


def is_real_package(pyproject: dict) -> bool:
    """False for a `[tool.uv] package = false` project (e.g. a UI-only app): it
    has no importable code of its own, so `-e .` must never be attempted --
    see the module docstring on the `.venv-local/lib/**/toy_ui-*` phantom
    package this omission was measured to produce otherwise."""
    return bool(pyproject.get("tool", {}).get("uv", {}).get("package", True))


def dependency_group_names(pyproject: dict) -> set[str]:
    """The `[dependency-groups]` table's own keys (not their contents)."""
    return set(pyproject.get("dependency-groups", {}).keys())


def em_dev_tool_config(pyproject: dict) -> dict | None:
    """The `[tool.em-dev]` table, or None if this repo hasn't opted into
    tool mode (the table a tool repo adds to its pyproject.toml)."""
    tool = pyproject.get("tool", {}).get("em-dev")
    return tool if isinstance(tool, dict) and tool.get("tool") else None


def platform_extras(tool_em_dev: dict, *, platform: str | None = None) -> list[str]:
    """The extras this platform needs, from `tool-extras = { win32 = [...] }`.
    Mirrors the branch a tool repo's CI os-matrix job takes:
    keyed on `sys.platform`, empty list (no extras) when unlisted."""
    plat = platform if platform is not None else sys.platform
    extras = tool_em_dev.get("tool-extras", {})
    return list(extras.get(plat, []))


def lock_packages(lock: dict) -> list[dict]:
    """The `[[package]]` entries of a parsed `uv.lock`."""
    return list(lock.get("package", []))


def discover_ours(lock: dict, own_name: str) -> list[str]:
    """Every `emergent-matter-*` package name in the lock, transitive
    included (materials arrives only via sdm-core, for example, and this
    reads the whole lock, not just direct dependencies), excluding this
    repo's own package. Sorted for stable, testable output."""
    names = set()
    for pkg in lock_packages(lock):
        name = pkg.get("name")
        if not name:
            continue
        norm = normalize_name(name)
        if norm.startswith(OURS_PREFIX) and norm != own_name:
            names.add(norm)
    return sorted(names)


def locked_version(lock: dict, name: str) -> str | None:
    """The version `uv.lock` records for `name` (normalized), or None."""
    norm = normalize_name(name)
    for pkg in lock_packages(lock):
        pkg_name = pkg.get("name")
        if pkg_name and normalize_name(pkg_name) == norm:
            version = pkg.get("version")
            return str(version) if version is not None else None
    return None


