def site_packages_dir(venv_dir: Path) -> Path | None:
    """The venv's site-packages, on whichever OS built it. Returns None if
    the venv doesn't look like it's been created yet."""
    win = venv_dir / "Lib" / "site-packages"
    if win.is_dir():
        return win
    lib = venv_dir / "lib"
    if lib.is_dir():
        for child in sorted(lib.iterdir()):
            candidate = child / "site-packages"
            if candidate.is_dir():
                return candidate
    return None


def find_dist_info(site_packages: Path, dist_name: str) -> Path | None:
    """The `<name>-<version>.dist-info` directory for `dist_name`
    (normalized), or None if it isn't installed there. Distribution
    directories on disk use underscores where the name has `-`/`.`/`_`, so
    this matches by normalizing each candidate rather than by literal glob."""
    if not site_packages.is_dir():
        return None
    norm = normalize_name(dist_name)
    for child in site_packages.iterdir():
        if not child.name.endswith(".dist-info"):
            continue
        candidate = re.sub(r"-[^-]+\.dist-info$", "", child.name)
        if normalize_name(candidate) == norm:
            return child
    return None


def installed_names(site_packages: Path) -> set[str]:
    """Every normalized distribution name with a `.dist-info` in
    `site_packages`."""
    if not site_packages.is_dir():
        return set()
    names = set()
    for child in site_packages.iterdir():
        if child.name.endswith(".dist-info"):
            names.add(normalize_name(re.sub(r"-[^-]+\.dist-info$", "", child.name)))
    return names


def unlocked_installs(venv_dir: Path, lock: dict, own_name: str) -> list[str]:
    """Anything installed into `venv_dir` that `uv.lock` never pinned at
    all -- a sibling that grew a new, unpinned third-party dependency (see
    the module docstring's "two passes" note). This is deliberately
    independent of whether the two-pass fallback ran: nothing about a
    brand-new, unpinned dependency necessarily conflicts with anything, so
    it can install cleanly in a single pass and still be worth naming.
    """
    site_packages = site_packages_dir(venv_dir)
    if site_packages is None:
        return []
    known = {own_name} | {normalize_name(p["name"]) for p in lock_packages(lock) if p.get("name")}
    return sorted(installed_names(site_packages) - known)


def is_editable_direct_url(dist_info_dir: Path) -> bool | None:
    """Whether a dist-info's `direct_url.json` marks an editable install.
    None if there's no direct_url.json (a normal registry wheel install
    doesn't always carry one) or it can't be read/parsed -- callers treat
    that as "not verifiably editable", never as an error.

    This one function is the entire "reverted local mode" detector: a
    console script (or `.venv-local` package) that em-dev put in editable
    mode reads editable=true here; anything that later reinstalled it from
    the registry (a plain `uv tool upgrade`, for example) reads false, and
    `status` reports the difference. Kept intentionally tiny and
    dependency-free so a tool's own status handler can copy it
    verbatim -- see the module docstring on why it isn't imported instead.
    """
    path = dist_info_dir / "direct_url.json"
    if not path.is_file():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    return bool(data.get("dir_info", {}).get("editable", False))


