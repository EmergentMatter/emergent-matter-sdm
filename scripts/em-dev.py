def _split_only(value: str) -> list[str]:
    return [v.strip() for v in value.split(",") if v.strip()]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="em-dev", description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--only",
        type=_split_only,
        default=None,
        metavar="a,b",
        help="Make only these packages local",
    )
    sub = ap.add_subparsers(dest="command")
    sub.add_parser("run", add_help=False).add_argument("cmd", nargs=argparse.REMAINDER)
    sub.add_parser("off")
    sub.add_parser("status")

    args, extra = ap.parse_known_args(argv)
    repo = Path.cwd()

    try:
        if args.command == "run":
            command = list(getattr(args, "cmd", []) or extra)
            return run_in_local(repo, command)
        if args.command == "off":
            return turn_off(repo)
        if args.command == "status":
            return status(repo)

        exit_code = make_local(repo, only=args.only)
        if exit_code != 0:
            return exit_code
        pyproject = toml_load(repo / "pyproject.toml")
        tool_cfg = em_dev_tool_config(pyproject)
        if tool_cfg is not None:
            print()
            return tool_on(repo, pyproject, tool_cfg)
        return 0
    except EmDevError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
