def tool_server_running(port: int = TOOL_PORT) -> bool:
    """Best-effort check for a tool server already listening on
    127.0.0.1:<port>. Named explicitly in every refusal message, since a
    reinstall while it's running is what leaves a locked, unreplaceable
    executable on Windows."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.settimeout(0.25)
        try:
            return s.connect_ex(("127.0.0.1", port)) == 0
        except OSError:
            return False


def console_script_name(pyproject: dict) -> str | None:
    scripts = pyproject.get("project", {}).get("scripts", {})
    if not scripts:
        return None
    # A repo opting into tool mode ships exactly one console script; take
    # the first (only) one rather than guessing which of several it means.
    return next(iter(scripts))


def local_checkout_defines_script(folder: Path, script_name: str) -> bool:
    """Whether `folder`'s own pyproject.toml still declares `script_name`
    under `[project.scripts]` -- checked before every tool reinstall, since
    `uv tool install --editable` silently *removes* the tool if it doesn't
    (see the plan's "How it works" step 5)."""
    pyproject_path = folder / "pyproject.toml"
    if not pyproject_path.is_file():
        return False
    data = toml_load(pyproject_path)
    return script_name in data.get("project", {}).get("scripts", {})


def tool_dirs(env: Mapping[str, str] | None = None) -> tuple[Path, Path]:
    """(UV_TOOL_DIR, UV_TOOL_BIN_DIR), resolved the same way `uv tool`
    would: respect the env vars when set (tests isolate them), otherwise
    ask uv directly -- never guess uv's own default location."""
    active_env = env if env is not None else os.environ
    tool_dir = active_env.get("UV_TOOL_DIR")
    bin_dir = active_env.get("UV_TOOL_BIN_DIR")
    if tool_dir and bin_dir:
        return Path(tool_dir), Path(bin_dir)
    proc = subprocess.run(
        ["uv", "tool", "dir"], capture_output=True, text=True, check=False, env=dict(active_env)
    )
    resolved_tool_dir = Path(tool_dir) if tool_dir else Path(proc.stdout.strip())
    proc2 = subprocess.run(
        ["uv", "tool", "dir", "--bin"],
        capture_output=True,
        text=True,
        check=False,
        env=dict(active_env),
    )
    resolved_bin_dir = Path(bin_dir) if bin_dir else Path(proc2.stdout.strip())
    return resolved_tool_dir, resolved_bin_dir


def index_args(pyproject: dict) -> list[str]:
    """`--index <url>` / `--find-links <url>` for every index this
    project's own `pyproject.toml` declares under `[tool.uv]`.

    `uv pip install -e .` run with `cwd=repo` picks this project's index
    config up on its own (measured); `uv tool install` does not -- it
    never reads the target project's `pyproject.toml` at all, editable or
    not, config file or none. Without this, `tool_on`/`tool_off` would
    only resolve `emergent-matter-*` dependencies when the real published
    index happened to also be configured globally (an env var, or a user-
    level uv.toml) rather than in this repo's own pyproject.toml, which is
    where the plan's "one source for environment values" style setup
    actually puts it. Passed explicitly so tool mode doesn't depend on
    that coincidence.
    """
    uv_cfg = pyproject.get("tool", {}).get("uv", {})
    args: list[str] = []
    for entry in uv_cfg.get("index", []):
        url = entry.get("url") if isinstance(entry, dict) else None
        if url:
            args += ["--index", url]
    for url in uv_cfg.get("find-links", []):
        args += ["--find-links", url]
    return args


def refuse_if_serve_running() -> None:
    """Guard shared by every tool reinstall, on or off: `serve` holds its
    own executable open (a locked file on Windows, an in-use binary
    everywhere else), so reinstalling it from under a running process is
    unsafe regardless of which direction the reinstall goes."""
    if tool_server_running():
        raise EmDevError(
            f"refusing to reinstall: something is already listening on "
            f"127.0.0.1:{TOOL_PORT} (a running tool server?) -- stop it first"
        )


def tool_on(repo: Path, pyproject: dict, tool_cfg: dict, *, quiet: bool = False) -> int:
    def out(msg: str = "") -> None:
        if not quiet:
            print(msg)

    refuse_if_serve_running()

    own_name = own_project_name(pyproject)
    script_name = console_script_name(pyproject)
    if script_name is None:
        raise EmDevError("[tool.em-dev] is set but pyproject.toml declares no [project.scripts]")
    if not local_checkout_defines_script(repo, script_name):
        raise EmDevError(
            f"this checkout's pyproject.toml no longer declares the "
            f"{script_name!r} console script -- `uv tool install --editable` "
            "would silently remove the tool instead of updating it"
        )

    lock = toml_load(repo / "uv.lock")
    ours = discover_ours(lock, own_name)
    config = load_config(repo)
    root = resolve_root(repo, config)
    resolutions = resolve_siblings(ours, root)
    out(f"sibling root: {root}")
    for r in resolutions:
        out(f"  {r.name:<40} -> {r.folder}  ({r.status})")
    locals_used = [r for r in resolutions if r.status == "local"]

    extras = platform_extras(tool_cfg)
    target = f".[{','.join(extras)}]" if extras else "."

    args = [
        "tool",
        "install",
        "--no-sources",
        "--force",
        "--editable",
        target,
        *index_args(pyproject),
    ]
    for r in locals_used:
        args += ["--with-editable", str(r.folder)]

    out(f"\nreinstalling the {script_name!r} tool from local code ...")
    run_uv(args, cwd=repo)
    out("done")
    return 0


def tool_off(repo: Path, pyproject: dict, tool_cfg: dict, *, quiet: bool = False) -> int:
    def out(msg: str = "") -> None:
        if not quiet:
            print(msg)

    refuse_if_serve_running()

    own_name = own_project_name(pyproject)
    version = own_project_version(pyproject)
    script_name = console_script_name(pyproject)
    if script_name is None:
        return 0
    out(f"reinstalling {own_name} {version} (published) as the {script_name!r} tool ...")
    # The exact version this repo pins, from pyproject.toml -- never
    # "latest": see the plan's "How it works" step 5. index_args() is why
    # this can find that version at all -- see its docstring.
    run_uv(
        ["tool", "install", "--force", f"{own_name}=={version}", *index_args(pyproject)], cwd=repo
    )
    out("done")
    return 0


def tool_status(repo: Path, pyproject: dict, tool_cfg: dict) -> list[str]:
    """Lines describing whether the console script's tool install is
    currently editable (local) or has reverted to a registry install --
    the "reverted local mode" detector from the plan's step 5/status note.
    """
    script_name = console_script_name(pyproject)
    own_name = own_project_name(pyproject)
    if script_name is None:
        return []
    tool_dir, _bin_dir = tool_dirs()
    # `uv tool install` names the tool environment after the DISTRIBUTION
    # (own_name), not the console script it happens to expose -- measured;
    # the two only look alike here because this org's console scripts are
    # usually named close to their package.
    env_dir = tool_dir / own_name
    site_packages = site_packages_dir(env_dir)
    lines = [f"tool ({script_name}):"]
    if site_packages is None:
        lines.append(f"  not installed as a tool (no {env_dir})")
        return lines
    dist_info = find_dist_info(site_packages, own_name)
    if dist_info is None:
        lines.append(f"  installed, but {own_name} not found in its environment")
        return lines
    editable = is_editable_direct_url(dist_info)
    if editable:
        lines.append("  local (editable)")
    elif editable is False:
        lines.append("  published -- local mode has reverted; run `em-dev` again")
    else:
        lines.append("  published (or unknown -- no direct_url.json)")
    return lines


