def run_in_local(repo: Path, command: list[str]) -> int:
    """`em-dev run <cmd...>`: run inside `.venv-local`, always `--no-sync`
    (a plain `uv run` re-syncs .venv-local back to published versions --
    measured; this is the one path that never does that).

    Uses `UV_PROJECT_ENVIRONMENT`, not `VIRTUAL_ENV` -- measured: `uv run`
    checks that `VIRTUAL_ENV` matches the project's own computed
    environment path (`.venv` by default) and, finding `.venv-local`
    doesn't, WARNS, ignores it, and creates and syncs a real `.venv`
    instead. `UV_PROJECT_ENVIRONMENT` is what actually redirects which
    environment `uv run` treats as the project's own.
    """
    venv_dir = repo / VENV_LOCAL
    if not (venv_dir / "pyvenv.cfg").is_file():
        make_local(repo)
    else:
        pyproject = toml_load(repo / "pyproject.toml")
        lock = toml_load(repo / "uv.lock")
        own_name = own_project_name(pyproject)
        ours = discover_ours(lock, own_name)
        config = load_config(repo)
        root = resolve_root(repo, config)
        locals_used = [r for r in resolve_siblings(ours, root) if r.status == "local"]
        if needs_rebuild(venv_dir, lock_hash(repo / "uv.lock"), locals_used):
            make_local(repo)

    if not command:
        raise EmDevError("em-dev run needs a command, e.g. `em-dev run pytest`")

    env = dict(os.environ)
    env["UV_PROJECT_ENVIRONMENT"] = str(venv_dir)
    bin_dir = venv_dir / ("Scripts" if os.name == "nt" else "bin")
    env["PATH"] = str(bin_dir) + os.pathsep + env.get("PATH", "")
    proc = subprocess.run(["uv", "run", "--no-sync", *command], cwd=repo, env=env, check=False)
    return proc.returncode


