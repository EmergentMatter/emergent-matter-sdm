def status(repo: Path) -> int:
    pyproject = toml_load(repo / "pyproject.toml")
    lock_path = repo / "uv.lock"
    lock = toml_load(lock_path)
    own_name = own_project_name(pyproject)
    ours = discover_ours(lock, own_name)

    if not ours:
        print("nothing here to make local (no emergent-matter-* dependency)")
        return 0

    config = load_config(repo)
    root = resolve_root(repo, config)
    resolutions = resolve_siblings(ours, root)

    print(f"sibling root: {root}")
    for r in resolutions:
        published = locked_version(lock, r.name)
        if r.status == "local":
            detail = sibling_git_detail(r.folder)
            print(f"  {r.name:<40} local   {r.folder} {detail}".rstrip())
        elif r.status == "missing":
            print(f"  {r.name:<40} published {published}  (no sibling folder at {r.folder})")
        else:
            print(f"  {r.name:<40} published {published}  ({r.folder} declares {r.found_name!r})")

    venv_dir = repo / VENV_LOCAL
    locals_used = [r for r in resolutions if r.status == "local"]
    if not (venv_dir / "pyvenv.cfg").is_file():
        print(f"\n{VENV_LOCAL}: not built -- run `em-dev`")
    elif needs_rebuild(venv_dir, lock_hash(lock_path), locals_used):
        print(f"\n{VENV_LOCAL}: stale -- run `em-dev` to rebuild")
    else:
        print(f"\n{VENV_LOCAL}: up to date")
        check_output = pip_check(repo, venv_dir)
        if check_output:
            print("uv pip check:")
            print(check_output)

    tool_cfg = em_dev_tool_config(pyproject)
    if tool_cfg is not None:
        print()
        for line in tool_status(repo, pyproject, tool_cfg):
            print(line)
    return 0


