# ============================================================================
# A minimal, stdlib-only TOML reader.
#
# Python's own `tomllib` needs 3.11+; this script's floor is 3.9 (see module
# docstring), so it cannot be used, and there is no stdlib TOML backport to
# fall back to on 3.9/3.10. Rather than carry two code paths (tomllib when
# available, this reader when not) that could quietly drift apart, this
# reader is used unconditionally, on every Python version -- one behavior to
# test and reason about.
#
# It is a subset of TOML v1.0: tables, array-of-tables, dotted keys, inline
# tables, arrays (incl. multi-line), basic/literal strings (incl. triple-
# quoted), integers, floats, booleans. Both files it ever reads are
# generated by uv (`uv.lock`) or hand-written to a small vocabulary
# (`pyproject.toml`'s `[project]`, `[tool.uv]`, `[tool.em-dev]`,
# `[dependency-groups]`): dates/times are accepted syntactically and
# returned as raw strings, since nothing here ever needs their value.
# ============================================================================


class TomlError(EmDevError):
    """The bundled TOML reader could not parse a file."""


_BARE_KEY_CHARS = frozenset("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-")
_NUMBER_STOP_CHARS = frozenset(",]}\r\n#") | frozenset(" \t")
_ESCAPES = {'"': '"', "\\": "\\", "n": "\n", "t": "\t", "r": "\r", "b": "\b", "f": "\f"}


class _TomlParser:
    """One-shot recursive-descent parser over a full TOML document string."""

    def __init__(self, text: str) -> None:
        self.s = text
        self.i = 0
        self.n = len(text)
        self.root: dict = {}
        self.current: dict = self.root

    def parse(self) -> dict:
        while True:
            self._skip_ws(newlines=True)
            if self.i >= self.n:
                break
            if self.s[self.i] == "[":
                self._parse_table_header()
            else:
                self._parse_keyval_line()
        return self.root

    # -------------------------------------------------------------- lexing

    def _skip_ws(self, *, newlines: bool) -> None:
        while self.i < self.n:
            c = self.s[self.i]
            if c in " \t" or (newlines and c in "\r\n"):
                self.i += 1
            elif c == "#":
                while self.i < self.n and self.s[self.i] not in "\r\n":
                    self.i += 1
            else:
                break

    def _skip_inline_ws(self) -> None:
        while self.i < self.n and self.s[self.i] in " \t":
            self.i += 1

    def _skip_to_eol(self) -> None:
        self._skip_inline_ws()
        while self.i < self.n and self.s[self.i] not in "\r\n":
            self.i += 1

    def _expect(self, ch: str) -> None:
        if self.i >= self.n or self.s[self.i] != ch:
            got = self.s[self.i] if self.i < self.n else "<eof>"
            raise TomlError(f"expected {ch!r} at position {self.i}, got {got!r}")
        self.i += 1

    # --------------------------------------------------------------- keys

    def _parse_key(self) -> str:
        self._skip_inline_ws()
        if self.i < self.n and self.s[self.i] in "\"'":
            return self._parse_string()
        start = self.i
        while self.i < self.n and self.s[self.i] in _BARE_KEY_CHARS:
            self.i += 1
        if start == self.i:
            raise TomlError(f"expected a key at position {self.i}")
        return self.s[start : self.i]

    def _parse_key_path(self) -> list[str]:
        keys = [self._parse_key()]
        self._skip_inline_ws()
        while self.i < self.n and self.s[self.i] == ".":
            self.i += 1
            keys.append(self._parse_key())
            self._skip_inline_ws()
        return keys

    # ------------------------------------------------------------- tables

    def _navigate(self, path: list[str], *, array_table: bool) -> dict:
        d = self.root
        for idx, key in enumerate(path):
            last = idx == len(path) - 1
            if last and array_table:
                lst = d.setdefault(key, [])
                if not isinstance(lst, list):
                    raise TomlError(f"{key!r} is already defined as a non-array table")
                new_tbl: dict = {}
                lst.append(new_tbl)
                return new_tbl
            existing = d.get(key)
            if existing is None:
                existing = {}
                d[key] = existing
            elif isinstance(existing, list):
                existing = existing[-1]  # descend into the most recent array-of-tables entry
            elif not isinstance(existing, dict):
                raise TomlError(f"{key!r} is already defined as a non-table value")
            d = existing
        return d

    def _parse_table_header(self) -> None:
        self._expect("[")
        is_array = False
        if self.i < self.n and self.s[self.i] == "[":
            is_array = True
            self.i += 1
        path = self._parse_key_path()
        self._expect("]")
        if is_array:
            self._expect("]")
        self.current = self._navigate(path, array_table=is_array)
        self._skip_to_eol()

    def _parse_keyval_line(self) -> None:
        path = self._parse_key_path()
        self._skip_inline_ws()
        self._expect("=")
        self._skip_inline_ws()
        value = self._parse_value()
        d = self.current
        for key in path[:-1]:
            nxt = d.get(key)
            if nxt is None:
                nxt = {}
                d[key] = nxt
            d = nxt
        d[path[-1]] = value
        self._skip_to_eol()

    # ------------------------------------------------------------- values

    def _parse_value(self) -> Any:  # returns one of several TOML value types
        self._skip_inline_ws()
        if self.i >= self.n:
            raise TomlError("expected a value, got end of input")
        c = self.s[self.i]
        if c in "\"'":
            return self._parse_string()
        if c == "[":
            return self._parse_array()
        if c == "{":
            return self._parse_inline_table()
        if self.s.startswith("true", self.i) and not self._is_bare_char_at(self.i + 4):
            self.i += 4
            return True
        if self.s.startswith("false", self.i) and not self._is_bare_char_at(self.i + 5):
            self.i += 5
            return False
        return self._parse_number_or_other()

    def _is_bare_char_at(self, pos: int) -> bool:
        return pos < self.n and self.s[pos] in _BARE_KEY_CHARS

    def _parse_string(self) -> str:
        quote = self.s[self.i]
        triple = self.s[self.i : self.i + 3] == quote * 3
        self.i += 3 if triple else 1
        literal = quote == "'"
        if triple and self.i < self.n and self.s[self.i] == "\n":
            self.i += 1  # a newline right after the opening delimiter is trimmed
        closing = quote * 3 if triple else quote
        out: list[str] = []
        while True:
            if self.s.startswith(closing, self.i):
                self.i += len(closing)
                return "".join(out)
            if self.i >= self.n:
                raise TomlError("unterminated string")
            ch = self.s[self.i]
            if not literal and ch == "\\":
                self.i += 1
                if self.i >= self.n:
                    raise TomlError("unterminated escape sequence")
                esc = self.s[self.i]
                if triple and esc in "\r\n":
                    self.i += 1
                    while self.i < self.n and self.s[self.i] in " \t\r\n":
                        self.i += 1
                    continue
                if esc in _ESCAPES:
                    out.append(_ESCAPES[esc])
                    self.i += 1
                elif esc == "u":
                    out.append(chr(int(self.s[self.i + 1 : self.i + 5], 16)))
                    self.i += 5
                elif esc == "U":
                    out.append(chr(int(self.s[self.i + 1 : self.i + 9], 16)))
                    self.i += 9
                else:
                    out.append(esc)
                    self.i += 1
            else:
                out.append(ch)
                self.i += 1

    def _parse_array(self) -> list:
        self._expect("[")
        items: list = []
        while True:
            self._skip_ws(newlines=True)
            if self.i < self.n and self.s[self.i] == "]":
                self.i += 1
                return items
            items.append(self._parse_value())
            self._skip_ws(newlines=True)
            if self.i < self.n and self.s[self.i] == ",":
                self.i += 1
                continue
            self._skip_ws(newlines=True)
            self._expect("]")
            return items

    def _parse_inline_table(self) -> dict:
        self._expect("{")
        d: dict = {}
        self._skip_inline_ws()
        if self.i < self.n and self.s[self.i] == "}":
            self.i += 1
            return d
        while True:
            self._skip_inline_ws()
            path = self._parse_key_path()
            self._skip_inline_ws()
            self._expect("=")
            self._skip_inline_ws()
            v = self._parse_value()
            cur = d
            for key in path[:-1]:
                cur = cur.setdefault(key, {})
            cur[path[-1]] = v
            self._skip_inline_ws()
            if self.i < self.n and self.s[self.i] == ",":
                self.i += 1
                continue
            self._skip_inline_ws()
            self._expect("}")
            return d

    def _parse_number_or_other(self) -> Any:
        start = self.i
        while self.i < self.n and self.s[self.i] not in _NUMBER_STOP_CHARS:
            self.i += 1
        tok = self.s[start : self.i]
        low = tok.lower()
        if low in ("inf", "+inf"):
            return float("inf")
        if low == "-inf":
            return float("-inf")
        if low in ("nan", "+nan", "-nan"):
            return float("nan")
        cleaned = tok.replace("_", "")
        if re.fullmatch(r"[+-]?\d+", cleaned):
            return int(cleaned)
        for prefix, base in (("0x", 16), ("0o", 8), ("0b", 2)):
            if cleaned.lower().startswith(prefix):
                return int(cleaned, base)
        try:
            return float(cleaned)
        except ValueError:
            # A date/time literal, or something unrecognized. Nothing this
            # script reads ever needs the parsed value of one -- returning
            # the raw token keeps the rest of the document parseable.
            return tok


def toml_loads(text: str) -> dict:
    """Parse a TOML document (the subset described in the module docstring)."""
    return _TomlParser(text).parse()


def toml_load(path: Path) -> dict:
    """Parse a TOML file, raising `EmDevError` with the path on failure."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise EmDevError(f"could not read {path}: {exc}") from None
    try:
        return toml_loads(text)
    except TomlError as exc:
        raise EmDevError(f"could not parse {path}: {exc}") from None


