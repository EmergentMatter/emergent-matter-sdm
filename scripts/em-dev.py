class SiblingResolution:
    """Where one `ours` package resolves to, and whether it's usable.

    status is one of:
        "local"          folder exists and its own pyproject.toml declares
                          this exact package name -- safe to install editable
        "missing"        no folder at the resolved path -- published version
                          used
        "name-mismatch"  a folder exists there, but declares a different
                          package name -- published version used, so a
                          same-named-but-wrong sibling folder can never be
                          installed under someone else's name
    """

    __slots__ = ("name", "folder", "status", "found_name")

    def __init__(self, name: str, folder: Path, status: str, found_name: str | None = None):
        self.name = name
        self.folder = folder
        self.status = status
        self.found_name = found_name

    def __repr__(self) -> str:  # pragma: no cover -- debugging aid only
        return f"SiblingResolution({self.name!r}, {self.folder!r}, {self.status!r})"


def load_config(repo: Path) -> dict:
    """The optional `.em-dev.toml`, or {} if absent. Deliberately never
    required to be gitignored via a tracked `.gitignore` edit -- see
    `ensure_local_gitignore`, which keeps it (and `.venv-local/`) out of
    `git status` through the repo's untracked `.git/info/exclude` instead."""
    path = repo / CONFIG_FILE
    if not path.is_file():
        return {}
    return toml_load(path)


def resolve_root(repo: Path, config: dict, env: Mapping[str, str] | None = None) -> Path:
    """Where sibling folders are looked for. `EM_DEV_ROOT` wins over
    `.em-dev.toml`'s `root`, which wins over the default: next to this
    repo. Per the plan's decision, this is never confirmed -- only always
    printed (see `resolve_siblings` callers), so a redirect is never
    silent without also being an interruption."""
    active_env = env if env is not None else os.environ
    root_env = active_env.get("EM_DEV_ROOT")
    if root_env:
        return Path(root_env).expanduser().resolve()
    root_cfg = config.get("root")
    if root_cfg:
        return (repo / root_cfg).resolve() if not Path(root_cfg).is_absolute() else Path(root_cfg)
    return repo.parent


def resolve_sibling(name: str, root: Path) -> SiblingResolution:
    """Resolve one `ours` package name to a folder under `root`, checking
    that the folder's own `pyproject.toml` actually declares that name."""
    folder = root / name
    if not folder.is_dir():
        return SiblingResolution(name, folder, "missing")
    pyproject_path = folder / "pyproject.toml"
    if not pyproject_path.is_file():
        return SiblingResolution(name, folder, "missing")
    try:
        data = toml_load(pyproject_path)
        found = normalize_name(data.get("project", {}).get("name", ""))
    except EmDevError:
        return SiblingResolution(name, folder, "missing")
    if found == name:
        return SiblingResolution(name, folder, "local", found)
    return SiblingResolution(name, folder, "name-mismatch", found)


def resolve_siblings(names: list[str], root: Path) -> list[SiblingResolution]:
    return [resolve_sibling(name, root) for name in names]


def filter_only(
    resolutions: list[SiblingResolution], only: list[str] | None
) -> list[SiblingResolution]:
    """Apply `--only a,b`: each token matches a resolution's full normalized
    name, or a `-`-delimited suffix of it (so "core" matches
    "emergent-matter-sdm-core"). Raises on an unknown or ambiguous token --
    silently installing nothing for a typo would be the exact silent no-op
    this org's tooling refuses to produce."""
    if not only:
        return resolutions
    selected: list[SiblingResolution] = []
    for token in only:
        norm = normalize_name(token)
        matches = [r for r in resolutions if r.name == norm or r.name.endswith("-" + norm)]
        if not matches:
            available = ", ".join(r.name for r in resolutions)
            raise EmDevError(f"--only {token!r} matches no package (have: {available})")
        if len(matches) > 1:
            names = ", ".join(m.name for m in matches)
            raise EmDevError(f"--only {token!r} is ambiguous: matches {names}")
        selected.append(matches[0])
    # De-duplicate while keeping first-seen order, in case two tokens
    # resolve to the same package.
    seen = set()
    out = []
    for r in selected:
        if r.name not in seen:
            seen.add(r.name)
            out.append(r)
    return out


