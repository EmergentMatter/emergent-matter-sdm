# git plumbing: local-only ignore, and sibling status detail
# ============================================================================


def ensure_local_gitignore(repo: Path) -> None:
    """Keep `.venv-local/` and `.em-dev.toml` out of `git status` via the
    repo's own untracked `.git/info/exclude`, never via a tracked
    `.gitignore` edit. `.venv-local/` doesn't strictly need this -- uv
    writes a `.gitignore` containing `*` inside every venv it creates, the
    same way it does for `.venv` -- but `.em-dev.toml` lives at the repo
    root and has nothing else to hide behind. Best-effort: a repo with no
    `.git` directory (a plain checkout, or a test fixture) is left alone.
    """
    git_dir = repo / ".git"
    if not git_dir.is_dir():
        return
    exclude_path = git_dir / "info" / "exclude"
    existing = exclude_path.read_text(encoding="utf-8") if exclude_path.is_file() else ""
    missing = [line for line in LOCAL_GITIGNORE_LINES if line not in existing.splitlines()]
    if not missing:
        return
    exclude_path.parent.mkdir(parents=True, exist_ok=True)
    sep = "" if existing.endswith("\n") or not existing else "\n"
    exclude_path.write_text(existing + sep + "\n".join(missing) + "\n", encoding="utf-8")


def git(args: list[str], cwd: Path) -> tuple[int, str]:
    p = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=False)
    return p.returncode, p.stdout.strip()


def sibling_git_detail(folder: Path) -> str:
    """A one-line `branch@sha (dirty)` summary for `status`, or "" if the
    folder isn't a git checkout."""
    code, branch = git(["rev-parse", "--abbrev-ref", "HEAD"], folder)
    if code != 0:
        return ""
    code, sha = git(["rev-parse", "--short", "HEAD"], folder)
    sha = sha if code == 0 else "?"
    code, dirty_out = git(["status", "--porcelain"], folder)
    dirty = " (uncommitted changes)" if code == 0 and dirty_out else ""
    return f"{branch}@{sha}{dirty}"


# ============================================================================
# uv subprocess helpers
# ============================================================================


def run_uv(
    args: list[str], *, cwd: Path, env: dict[str, str] | None = None, check: bool = True
) -> subprocess.CompletedProcess:
    """Run `uv <args>`, merged over the current environment plus `env`."""
    full_env = dict(os.environ)
    if env:
        full_env.update(env)
    proc = subprocess.run(
        ["uv", *args], cwd=cwd, env=full_env, capture_output=True, text=True, check=False
    )
    if check and proc.returncode != 0:
        raise EmDevError(
            f"`uv {' '.join(args)}` failed (exit {proc.returncode}):\n{proc.stderr.strip()}"
        )
    return proc


def uv_venv(venv_dir: Path, *, cwd: Path) -> None:
    """Create `.venv-local` if it doesn't already exist. Resolves the
    interpreter the same way `uv sync` would for `.venv` (requires-python,
    `.python-version`, etc.) -- nothing here pins a Python version, so a
    consumer's own floor is respected without duplicating it here."""
    if (venv_dir / "pyvenv.cfg").is_file():
        return
    run_uv(["venv", str(venv_dir)], cwd=cwd)


def export_constraints(repo: Path, out_path: Path, *, skip_names: list[str]) -> None:
    """`uv export --frozen ...`, excluding `skip_names` (the packages about
    to be installed editable) -- see the module docstring's "two passes"
    note. `--frozen` means this never re-resolves or touches `uv.lock`."""
    args = [
        "export",
        "--frozen",
        "--no-hashes",
        "--no-emit-project",
    ]
    for name in skip_names:
        args += ["--no-emit-package", name]
    args += ["-o", str(out_path)]
    run_uv(args, cwd=repo)


def pip_install(
    repo: Path, venv_dir: Path, args: list[str], *, check: bool = True
) -> subprocess.CompletedProcess:
    """`--no-sources` only, deliberately not `--no-config` too: measured
    against a local test index, `--no-config` disables discovering
    `pyproject.toml` outright, which also throws away this repo's own
    `[tool.uv]` index/find-links declaration -- the one thing that lets
    `uv pip install` reach the real published index at all. `--no-sources`
    alone still reads `pyproject.toml`, but ignores only its
    `[tool.uv.sources]` table (path/git/workspace overrides), which is
    exactly and only what must not leak into this install."""
    return run_uv(
        ["pip", "install", "--no-sources", *args],
        cwd=repo,
        env={"VIRTUAL_ENV": str(venv_dir)},
        check=check,
    )


def pip_check(repo: Path, venv_dir: Path) -> str:
    """`uv pip check`'s text output, or "" when it reports nothing wrong."""
    proc = run_uv(["pip", "check"], cwd=repo, env={"VIRTUAL_ENV": str(venv_dir)}, check=False)
    return (proc.stdout + proc.stderr).strip()


