def lock_hash(lock_path: Path) -> str:
    return hashlib.sha256(lock_path.read_bytes()).hexdigest()


def state_path(venv_dir: Path) -> Path:
    return venv_dir / STATE_FILE


def read_state(venv_dir: Path) -> dict | None:
    path = state_path(venv_dir)
    if not path.is_file():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def write_state(venv_dir: Path, state: dict) -> None:
    state_path(venv_dir).write_text(
        json.dumps(state, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def _sibling_state_rows(locals_used: list[SiblingResolution]) -> list[dict]:
    return [{"name": r.name, "folder": str(r.folder)} for r in locals_used]


def build_state(lock_hash_value: str, locals_used: list[SiblingResolution]) -> dict:
    return {
        "uv_lock_hash": lock_hash_value,
        "siblings": _sibling_state_rows(locals_used),
    }


def needs_rebuild(
    venv_dir: Path, lock_hash_value: str, locals_used: list[SiblingResolution]
) -> bool:
    """True when `.venv-local` is missing, or its recorded state no longer
    matches the current lock hash and sibling list -- see the module
    docstring's "Freshness" note. This is also what makes a stale prior
    build safe to just overwrite: nothing here trusts .venv-local's content
    once its state file disagrees with the world."""
    if not (venv_dir / "pyvenv.cfg").is_file():
        return True
    state = read_state(venv_dir)
    if state is None:
        return True
    if state.get("uv_lock_hash") != lock_hash_value:
        return True
    current = sorted(tuple(sorted(d.items())) for d in _sibling_state_rows(locals_used))
    stored = sorted(tuple(sorted(d.items())) for d in state.get("siblings", []))
    return stored != current


